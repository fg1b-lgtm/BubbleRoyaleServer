// 조각마다 좌우/상하 뒤집기가 따로 걸려서, 같은 조각도 매번 다르게 보인다.
//   10개 중 9개를 고르는 경우의 수 x 자리 바꾸기 x 뒤집기 = 매판 다른 판이 나온다
//
// 글자의 뜻
//   #  고정 벽. 절대 안 부서진다
//   .  반드시 통로. **길**이다. 여기에는 블록을 깔지 않는다
//   ?  확률로 블록 (BLOCK_FILL_PERCENT)
//   s  스폰 자리. 통로이기도 하다
//
// 조각마다 지키는 약속 (tools/maptest.cpp 가 매판 다시 잰다)
//   ① 관문 네 곳 (7,0) (7,12) (0,6) (14,6) 은 길이다.
//      좌우로 뒤집으면 (0,6) 과 (14,6) 이 자리를 바꾸고, 위아래로 뒤집으면
//      (7,0) 과 (7,12) 가 자리를 바꾼다. 어느 쪽으로 뒤집어도 관문은 관문이다.
//      조각을 붙이면 아래 조각의 (7,12) 와 위 조각의 (7,0) 이 바로 맞닿는다.
//   ② 길(.) 만으로 관문 넷과 스폰 셋이 전부 이어진다.
//      블록이 최악으로 깔려도 시작하자마자 갇히지 않는다는 뜻이다.
//   ③ 스폰은 x 3..11, y 3..9 안에만 둔다.
//      경계에 붙여두면 옆 조각 스폰과 세 칸 거리가 된다. 사거리가 2 이니 시작하자마자 사정권이다.
//   ④ 벽으로 갈라진 칸이 없다.
//
// 소유 스레드 : 없음. 읽기만 하는 상수다
