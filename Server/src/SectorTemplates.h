// Server/src/SectorTemplates.h — 손으로 그린 맵 조각
//
// 9/4: 서른한 종을 지웠다. 사람이 그림으로 정확히 보내준 판만
// 남기고 시험한다. 나머지는 작성자가 하나씩 새로 그려서 줄 예정이다 —
// 지금은 "그림 그대로 배치했나" 를 확인하는 단계다.
//
// 지운 스물아홉 종은 사라진 게 아니다. git 로그에 그대로 있다
// (`git show <이전 커밋>:Server/src/SectorTemplates.h`).
//
// 조각을 손으로 그렸다. 세 종을 아홉 자리에 반복해 뽑아 3x3 으로 붙인다.
// 조각마다 좌우/상하 뒤집기가 따로 걸려서, 같은 조각도 매번 다르게 보인다.
//
// 글자의 뜻
//   #  고정 벽. 절대 안 부서진다
//   .  반드시 통로. **길**이다. 여기에는 블록을 깔지 않는다
//   ?  확률로 블록 (BLOCK_FILL_PERCENT)
//   s  스폰 자리. 통로이기도 하다
//   ~  강. 규칙으로는 # 과 똑같은 벽이고, 화면에만 물로 보인다
//   =  다리. 규칙으로는 . 과 똑같은 길이고, 화면에만 다리로 보인다
//   b  정해진 블록. ? 와 달리 **확률이 아니라 항상 거기 있다**
//   p  정해진 상자(밀 수 있는 것). b 와 같되 밀 수 있다는 것만 다르다
//
// ~ 와 = 은 규칙을 하나도 안 늘린다. 강을 규칙에 넣으면 "지나갈 수 있나" 를
// 두 군데서 보게 되고, 두 곳이 어긋나는 날 사람이 벽을 뚫는다.
// 겉모습은 겉모습으로만 나간다 (GameMap 의 look, MAPROW 의 넷째 줄).
//
// b/p 는 사람이 그려온 판(마을·사막·얼음골)에 쓴다. 그 그림은 상자 하나하나가 그
// 자리에 있으라고 그린 것이지 "대충 이 근방에 몇 개" 가 아니다. ? 로 두면
// 매판 다른 자리에 나서 그림과 달라진다
//
// 조각마다 지키는 약속 (tools/maptest.cpp 가 매판 다시 잰다)
//   ① 관문 네 곳 (7,0) (7,12) (0,6) (14,6) 은 길이다.
//      좌우로 뒤집으면 (0,6) 과 (14,6) 이 자리를 바꾸고, 위아래로 뒤집으면
//      (7,0) 과 (7,12) 가 자리를 바꾼다. 어느 쪽으로 뒤집어도 관문은 관문이다.
//      조각을 붙이면 아래 조각의 (7,12) 와 위 조각의 (7,0) 이 바로 맞닿는다.
//   ② 길(.=s) 만으로 관문 넷과 스폰이 전부 이어진다.
//      블록이 최악으로 깔려도 시작하자마자 갇히지 않는다는 뜻이다.
//   ③ 스폰은 x 3..11, y 3..9 안에만 둔다.
//      경계에 붙여두면 옆 조각 스폰과 세 칸 거리가 된다. 사거리가 2 이니 시작하자마자 사정권이다.
//   ④ 벽(#)으로 갈라진 칸이 없다.
//
// 소유 스레드 : 없음. 읽기만 하는 상수다
#pragma once

#include "GameConstants.h"

// 판의 총수. 지금은 마을·사막·얼음골 세 종이고 각자 자기 테마 하나씩만 쓴다
constexpr int SECTOR_TEMPLATE_COUNT = 3;
constexpr int SECTOR_THEME_COUNT    = 10;

// 벽이 뭉친 자리에 집·우물·텐트·장터 같은 큰 그림을 얹는다(web/art.js 의
// place.tiles.big). 예전엔 화면이 "벽이 W x H 만큼 꽉 찬 자리"를 스스로
// 찾아서 그 크기에 맞는 그림 중 하나를 무작위로 얹었다.
//
// 그런데 마을은 집(2x2)과 우물(2x2)이 **크기가 같다.** 화면은 벽 모양만
// 보고는 "이 자리가 집 자리였는지 우물 자리였는지" 를 가릴 방법이 없어서,
// 찾아낸 아무 2x2 벽 덩어리에나 집 아니면 우물을 반반 확률로 얹었다.
// 강가·조각 이음매처럼 우연히 벽이 뭉친 자리까지 걸려서, 한 판에 우물
// 대여섯 채가 서고 집은 하나도 안 서는 일이 실제로 나왔다 - 사진과 전혀
// 다른 마을이 된 원인이 이거였다.
//
// 그래서 "여기, 이 이름" 을 조각을 그릴 때 못 박아 클라이언트로 그대로
// 보낸다(PKT_LANDMARKS, GameMap::landmarks). 화면은 더는 벽 모양을 보고
// 추측하지 않는다.
//
// kind 는 web/artdata.js 그 테마의 tiles.big 배열 순번이다(0, 1, 2 ...).
// 같은 kind 를 조각 하나에 여러 번 써도 된다 - 마을 집 두 채가 둘 다
// kind 0("집")이듯, 그림은 같되 서는 자리만 다른 경우다.
// x, y 는 조각 안 왼쪽 위 칸이고, **뒤집기 전** 기준이다 - 뒤집는 계산은
// GameMap::StampSector 가 조각을 붙일 때 한 번만 한다
struct SectorLandmark
{
    uint8_t kind;
    uint8_t x, y;
    uint8_t w, h;   // 뒤집을 때 왼쪽 끝을 다시 구하는 데 쓴다 (GameMap::StampSector)
};
constexpr int MAX_LANDMARK = 4;

struct SectorTemplate
{
    const char* name;

    // 어느 테마의 판인가. 0 광장 1 사원 2 공장 3 마을 4 캠프
    //                    5 사막 6 시장 7 해변 8 얼음골 9 부두
    //
    // **테마와 판을 나눈 이유.**
    //
    // 전에는 판 하나에 테마 하나였다. 그래서 마을은 늘 같은 골목이었다.
    // 크아를 보면 빌리지가 1부터 10까지 있고 캠프도 여럿이다 —
    // 색과 물건은 같은데 길이 다르다. 그래야 '마을' 이 한 장소가 아니라
    // 여러 번 가본 동네가 된다.
    //
    // 판을 고를 때 테마가 안 겹치게만 고른다. 같은 판에 마을이 둘이면
    // 어디가 어딘지 모른다 — 사람이 길을 외우는 단위가 테마이기 때문이다.
    //
    // 지금은 조각이 둘뿐이라 테마도 둘만 쓰인다(3, 5). 나머지 여덟 자리는
    // GameMap::Generate 가 "템플릿이 있는 테마만" 추려서 돌려 쓴다
    int theme;

    const char* row[SECTOR_H];

    SectorLandmark landmark[MAX_LANDMARK];
    int landmark_count;
};

