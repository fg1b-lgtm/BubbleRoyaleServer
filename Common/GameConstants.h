// 봇 시뮬레이션으로 밸런스를 맞출 때 이 파일만 고치며 돌린다.
// 서버와 클라이언트가 같은 값을 봐야 같은 판정이 나오므로 Common 에 둔다.
#pragma once

#include <cstdint>

// ── 시뮬레이션 ─────────────────────────────────────────────
constexpr int TICK_RATE  = 30;    // 초당 몇 번 도나
constexpr int TILE_UNITS = 256;   // 타일 하나를 몇 칸으로 쪼개나 (고정소수점)

// 캐릭터 몸 크기. 타일 하나의 몇 배인가.
//
// 판정은 간단하다. **몸의 과반수가 있는 칸이 내가 있는 칸**이다.
// 몸이 중심을 기준으로 대칭이면 그건 곧 중심이 있는 칸이라, 계산이 필요 없다.
//
// 그럼 걸치기는 어디서 나오나.
//   몸은 타일보다 작아서 두 칸에 걸쳐 설 수 있다.
//   물줄기는 칸 단위로 덮는다.
//   그래서 몸은 물에 닿았는데 중심은 안전한 칸에 있는 순간이 생긴다. 그게 걸치기다.
//
// 이 값은 판정을 바꾸지 않는다. 몸이 얼마나 걸쳐 보이는지만 정한다.
//   작으면 걸쳐 있다는 게 눈에 잘 안 보인다
//   1.0 이면 늘 두 칸에 걸쳐 보여서 걸치기가 특별해 보이지 않는다
// float 를 안 쓰려고 분자/분모로 나눠 둔다. 서버와 클라가 같은 답을 내야 한다.
//
// 0.68 로 두고 돌려보니 캐릭터가 통로 안에서 너무 작아 보였다.
// 화면이 인형이 아니라 점 같았고, 맞았는지 스쳤는지가 눈에 잘 안 들어왔다.
// 0.80 이면 통로(1.0)를 거의 채운다. 양옆으로 0.1 씩만 남는다.
//   - 몸이 크니 걸치기가 더 자주 난다. 이 게임에서 제일 큰 리턴이 더 자주 온다
//   - 대신 코너에 더 잘 걸린다. 그래서 코너 보정(CORNER_ASSIST)이 더 중요해졌다
//   - 몸으로 부딪쳐 터뜨리는 거리(POP_TOUCH_DIST)도 같이 커진다. 마무리가 쉬워진다
constexpr int PLAYER_BODY_NUM = 80;    // 0.80 타일
constexpr int PLAYER_BODY_DEN = 100;

// 몸의 절반 길이. 중심에서 이만큼씩 뻗는다
constexpr int PLAYER_HALF = TILE_UNITS * PLAYER_BODY_NUM / (PLAYER_BODY_DEN * 2);

// ── 맵 ─────────────────────────────────────────────────────
constexpr int SECTOR_W = 15;   // 맵 조각 하나의 가로. 크레이지아케이드 원본 크기
constexpr int SECTOR_H = 13;
constexpr int SECTOR_COLS = 3; // 조각을 3x3 으로 붙인다
constexpr int SECTOR_ROWS = 3;
constexpr int MAP_W = SECTOR_W * SECTOR_COLS;   // 45
constexpr int MAP_H = SECTOR_H * SECTOR_ROWS;   // 39

constexpr int PLAYER_MAX = 24;

// 타일 한 칸에 무엇이 있나. 맵은 이 값들로만 채워진다
enum TileType : uint8_t
{
    TILE_EMPTY = 0,   // 통로
    TILE_WALL  = 1,   // 고정 벽. 드릴 말고는 못 부순다
    TILE_BLOCK = 2,   // 파괴 가능 블록. 부수면 확률로 아이템이 나온다

    // 놓인 물풍선도 칸을 막는다. 물줄기도 여기서 멈춘다.
    //
    // 놓은 사람은 그 칸에서 나갈 수 있고 나가면 다시 못 들어온다.
    // 따로 예외를 두지 않았는데도 그렇게 된다.
    // 이동 판정이 "지금 있는 칸" 이 아니라 "가려는 칸" 만 보기 때문이다.
    TILE_BUBBLE = 3,

    // 밀 수 있는 상자. 부서지기도 한다.
    //
    // 블록은 부수는 것 말고는 할 게 없다. 길을 막고 있으면 폭탄을 놓고 기다린다.
    // 상자는 **밀 수 있다.** 그래서 같은 벽 하나에 선택지가 둘이 된다.
    //   부순다   2.5초 걸리고 아이템이 나올 수도 있다
    //   민다     즉시. 대신 민 자리에 그대로 있다
    //
    // 밀어서 통로를 막을 수도 있고, 물에 밀어 넣을 수도 있고,
    // 쫓기는 중에 뒤로 밀어 길을 끊을 수도 있다.
    // 규칙 하나로 판단거리가 여럿 생기는 쪽이 좋은 규칙이다
    TILE_BOX = 4,
};

// 부술 수 있는 칸인가. 블록과 상자 둘 다다
inline bool IsBreakableTile(uint8_t t) { return t == TILE_BLOCK || t == TILE_BOX; }

// 맵 조각 하나에 스폰 자리 3개. 3x3 조각이니 전체 27 자리에 24명이 들어간다
constexpr int SPAWN_PER_SECTOR = 3;
constexpr int SPAWN_TOTAL      = SPAWN_PER_SECTOR * SECTOR_COLS * SECTOR_ROWS;

// 파괴 가능 블록을 조각이 '?' 로 남겨둔 자리 중 몇 퍼센트에 깔 것인가.
//
// 블록은 아이템 상자이자 시계다. 부술수록 맵이 열리면서 게임이 가속한다.
// 그래서 이 값 하나가 아이템 총량과 시작의 답답함을 동시에 정한다.
// tools/maptest.exe 가 밀도별 표를 찍어준다. 50 은 그 표를 보고 고른 값이다.
//
//   블록 270개 -> 아이템 108개 -> 24명이 나눠서 한 사람당 네다섯 개
//   스폰에서 밖으로 나가는 데 최대 1겹 (2.5초)
//
// 9/1 에 50 에서 100 으로 올렸다. **고정 벽과 스폰 자리 빼고 전부 상자다.**
//
// 50 일 때는 시작하자마자 길이 뚫려 있어서 서로 30초 만에 만났다.
// 크아도 봄버맨도 시작은 상자에 둘러싸인 채다. 그게 앞의 1분을 만든다.
//   - 파낸 만큼만 갈 수 있으니 **판이 시간에 따라 열린다**
//   - 상자가 곧 아이템이라 파는 것 자체가 보상이다
//   - 물줄기 사거리가 1 이라 한 번에 하나씩만 부순다. 서두를 수가 없다
//
// 조각에 그린 길('.')도 이제 상자로 덮인다. 길은 파고 나면 드러난다.
// 시작하자마자 안 갇히는 것은 스폰 주변을 비우는 것과
// OpenDeathTraps 가 보장한다 (SPEC 2.2).
constexpr int BLOCK_FILL_PERCENT = 100;

// 깔린 블록 중 몇 퍼센트를 **밀 수 있는 상자**로 바꿀 것인가.
//
// 너무 많으면 판이 물러서 벽이 의미를 잃고, 너무 적으면 있는 줄도 모른다.
// 다섯 칸에 하나쯤이면 한 화면에 서너 개라 눈에 띄면서 흔하지는 않다
constexpr int BOX_PERCENT = 20;

// 상자를 한 번 밀고 나서 다음까지 몇 틱 쉬나.
// 없으면 붙어서 계속 누르는 동안 상자가 주르륵 밀려간다. 한 번에 한 칸이어야 판단이 된다
constexpr int PUSH_COOLDOWN_TICKS = TICK_RATE / 3;


// 스폰 자리 주변 몇 칸을 비워두는가.
//
// 1 이면 3x3 이다. 이 크기여야 한다.
//   가운데에 물풍선을 놓으면 사거리 1 짜리 물줄기가 십자로 네 칸을 덮는다.
//   **네 귀퉁이는 안 덮인다.** 그래서 첫 물풍선을 놓고 대각선으로 피할 수 있다.
// 2 로 하면 너무 넓어서 시작이 안 답답하고, 0 이면 놓는 순간 죽는다
constexpr int SPAWN_CLEAR_RADIUS = 1;

// 스폰 주변 반경 3 안의 블록 수를 이 폭 안으로 맞춘다.
// 누구는 여덟 개고 누구는 둘이면 1분 뒤 아이템 차이가 그대로 실력 차이로 보인다.
// 대칭은 예쁘라고 하는 게 아니라 억울함을 없애는 장치다 (SPEC 2.2)
constexpr int SPAWN_BLOCK_TOLERANCE = 3;

// ── 이동 ───────────────────────────────────────────────────
//
// 속도는 "한 틱에 몇 units 가나" 로 적는다.
// "초당 몇 타일" 로 적으면 TICK_RATE 를 바꿀 때 전부 틀어진다.
//
//   24 units/tick * 30 tick/s / 256 units/tile = 2.8 타일/초
//   롤러를 상한(4)까지 먹으면 40 -> 4.7 타일/초
//
// 한 틱 이동량이 TILE_UNITS 보다 훨씬 작아야 한다.
// 크면 벽을 한 틱에 뛰어넘는다. 40 은 256 의 1/6 이라 안전하다.
//
// 9/1 에 24 에서 18 로 낮췄다. 24 는 2.8 타일/초인데 통로 폭이 한 칸이라
// 코너에서 계속 흘러넘쳤다. 느려지면 **어디에 설지**를 고를 수 있게 된다.
// 봄버맨류에서 속도는 빠를수록 좋은 게 아니라, 칸에 맞춰 설 수 있어야 좋은 것이다.
//   18 -> 2.1 타일/초.  롤러 상한까지 먹으면 34 -> 4.0 타일/초
constexpr int MOVE_SPEED_BASE = 18;

// 상자가 밀리기까지 버텨야 하는 시간, 그리고 밀려가는 데 걸리는 시간.
//
// 전에는 방향을 대는 순간 상자가 옆 칸으로 순간이동했다. 미는 것처럼 안 보였고,
// 지나가다 살짝 스치기만 해도 상자가 튀어서 판이 제멋대로 바뀌었다.
//
// 0.5초를 버텨야 움직이기 시작한다. 그만큼 서 있어야 하므로 미는 것이
// **의도한 행동**이 되고, 그 0.5초 동안 옆에서 오는 사람에게는 표적이 된다.
//
// 밀려가는 속도는 사람의 최저 이동 속도와 같다. 상자보다 사람이 느릴 수는 없고,
// 빠르면 상자가 사람을 앞질러서 뭘 미는 건지 안 보인다
constexpr int PUSH_CHARGE_TICKS = TICK_RATE / 2;
constexpr int PUSH_SLIDE_TICKS  = (TILE_UNITS + MOVE_SPEED_BASE - 1) / MOVE_SPEED_BASE;

constexpr int MOVE_SPEED_STEP = 4;    // 롤러 하나당 붙는 양

// 갇혔을 때의 속도.
//
// 아예 못 움직이게 하면 5초가 그냥 죽은 시간이 된다.
// 느리게라도 갈 수 있어야 "물줄기 밖으로 기어나갈까" 가 판단거리가 된다.
// SPEC 2.4 가 갇힘을 기다리는 시간이 아니라 판단하는 시간이라고 한 이유다.
constexpr int TRAP_MOVE_SPEED = 6;    // 0.7 타일/초. 기본의 1/4

// 갇힌 사람을 터뜨리는 데 필요한 접촉 거리.
//
// 물줄기로는 갇힌 사람을 더 어쩌지 못한다. **몸으로 부딪쳐야 터진다.** 크아가 그렇다.
// 그래서 마무리하려면 거리를 좁혀야 하고, 좁히는 동안 내가 위험해진다.
// 갇힌 사람이 기어서 도망가는 것도 그래서 의미가 생긴다.
constexpr int POP_TOUCH_DIST = PLAYER_HALF * 2;

// 코너 보정. **껐다.**
//
// 원래는 가려는 쪽이 막혔을 때 옆으로 살짝 밀어 모서리를 돌게 해줬다.
// 봄버맨류에서 손맛의 대부분이 거기서 나온다고 알려져 있고, 그래서 90 으로 켜뒀다.
//
// 9/1 에 몸이 벽을 못 넘게 바꾸면서 이 값을 128 로 올렸다.
// 통로 안에서 중심이 102~154 에만 있을 수 있어서 90 으로는 조건에 안 닿았기 때문이다.
//
// 그러고 돌려보니 **벽에 조금만 비벼도 대각선으로 스윽 미끄러졌다.**
// 벽에 닿으면 서야 하는데 벽을 타고 흘렀다. 원하는 칸에 설 수가 없다.
//
// 0 으로 끈다. 이 게임은 칸에 맞춰 서는 게 중요한 게임이다.
// 물풍선을 어느 칸에 놓을지가 판단의 전부인데, 서고 싶은 데 못 서면 그게 무너진다.
// 도와주는 대신 **몸이 벽에 안 걸치게** 해서 통로가 넓어 보이는 문제를 없앴다.
//
//   0    벽에 닿으면 선다. 지금 이것
//   90   반 칸쯤 어긋나 있으면 돌아진다
//   128  옆이 뚫려 있으면 언제나 붙는다. 너무 미끄럽다
constexpr int CORNER_ASSIST = 0;

// 줄 맞춤. 가는 축과 **직각인** 축을 지금 칸 한가운데로 천천히 당긴다.
//
// 코너 보정을 끄고 나니 통로를 못 지나가게 됐다.
// 통로가 한 칸(256)인데 몸이 204 라, 지나가려면 중심이 102~154 사이 52칸에
// 들어와 있어야 한다. 한 칸의 20% 다. 키보드로 그걸 맞출 수는 없다.
//
// 코너 보정과 **다른 점이 하나 있는데 그게 전부다.**
//   코너 보정 : 옆 칸으로 민다  -> 벽에 비비면 다른 줄로 미끄러진다
//   줄 맞춤   : 내 칸 한가운데로 당긴다 -> 줄을 절대 안 벗어난다
//
// 그래서 "벽에 닿으면 선다" 를 지키면서도 통로에 들어갈 수 있다.
// 줄을 바꾸는 일은 여전히 사람이 직접 누른다.
//
// 이동 속도의 몇 퍼센트로 당길 것인가. 100 이면 순간이동처럼 붙고, 0 이면 안 당긴다.
// 50 이면 52칸을 메우는 데 여섯 틱(0.2초)이라 당겨지는 게 눈에 안 거슬린다
constexpr int LANE_SNAP_PERCENT = 50;

// ── 물풍선 ─────────────────────────────────────────────────
constexpr int MAX_BUBBLE        = PLAYER_MAX * 6;   // 사람당 최대 5개 + 여유
constexpr int BUBBLE_BASE_COUNT = 1;   // 아이템 없이 동시에 놓을 수 있는 수
// 아이템 없이 물줄기가 뻗는 칸 수.
//
// 9/1 에 2 에서 1 로 낮췄다. 시작 물줄기가 사방 한 칸이면
